#!/usr/bin/env python3
"""Generate src/gallery/index.html from src/gallery/lessons.json.

Run locally after editing lessons.json and commit both files:

    python3 tools/build-gallery.py

Standard library only. The lesson files themselves are NOT committed here: the
download links point at the egatari/examples release, and 「ブラウザで見る」 opens
/gallery/play/?id=<id> (each lesson's playUrl), which plays the play-only file
that the site build fetched and checked against src/gallery/samples.lock.json
(tools/gallery_files.py). Set "play_live": false in lessons.json to show the
「ブラウザで見る（準備中）」 placeholders instead.
"""
from __future__ import annotations

import json
import sys
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "src" / "gallery" / "lessons.json"
OUT = ROOT / "src" / "gallery" / "index.html"

LANG_LABEL = {"en": "英語"}

HEAD = """<!DOCTYPE html>
<html lang="ja">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>見本：Egatari</title>
<meta name="description" content="Egatari で作った教材の見本。">
<meta name="color-scheme" content="light dark">
<link rel="icon" href="/assets/logo/egatari-light.svg" type="image/svg+xml">
<link rel="stylesheet" href="/assets/site.css">
</head>
<body>
<!-- Generated by tools/build-gallery.py from lessons.json. Do not edit by hand. -->
<a class="skip" href="#main">本文へ</a>

<p class="notice">Egatari 1.0 の仕様は作業中の草案です。<a href="/spec/">仕様を読む</a></p>

<header>
  <div class="wrap site-head">
    <a class="brand" href="/"><picture><source srcset="/assets/logo/egatari-dark.svg" media="(prefers-color-scheme: dark)"><img src="/assets/logo/egatari-light.svg" alt="" width="48" height="48"></picture>Egatari</a>
    <nav class="site-nav" aria-label="サイト">
      <a href="/gallery/" aria-current="page">見本</a>
      <a href="/spec/">仕様</a>
      <a href="https://github.com/egatari">GitHub</a>
    </nav>
  </div>
</header>

<main id="main">
"""

FOOT = """</main>

<footer class="site-foot">
  <div class="wrap">
    <p>© 2026 Gendo Kumoi ・ サイトの文と画像は CC BY 4.0（ロゴを除く）</p>
    <ul>
      <li><a href="/spec/">仕様</a></li>
      <li><a href="https://github.com/egatari">GitHub</a></li>
      <li><a href="/gallery/">見本</a></li>
    </ul>
  </div>
</footer>
</body>
</html>
"""


def card(lesson: dict, base: str, play_live: bool) -> str:
    lid = lesson["id"]
    title = escape(lesson["title"])
    lang = lesson.get("lang", "ja")
    title_html = title if lang == "ja" else f'<span lang="{escape(lang)}">{title}</span>'
    tag = (
        f' <span class="lang">{escape(LANG_LABEL.get(lang, lang))}</span>' if lang != "ja" else ""
    )
    play = (
        f'<li><a href="{escape(lesson["playUrl"])}">ブラウザで見る</a></li>'
        if play_live
        else '<li class="soon"><span>ブラウザで見る（準備中）</span></li>'
    )
    return f"""      <li class="card">
        <img src="/gallery/{escape(lesson["cover"])}" width="640" height="360" alt="{title}の表紙" loading="lazy">
        <h3 id="l-{escape(lid)}">{title_html}{tag}</h3>
        <ul aria-labelledby="l-{escape(lid)}">
          <li><a href="{escape(base + lesson["portable"])}">ダウンロード（編集できる版）</a></li>
          <li><a href="{escape(base + lesson["play"])}">ダウンロード（見るだけの版）</a></li>
          {play}
        </ul>
      </li>
"""


def main() -> int:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    base = data["download_base"]
    sections = data["sections"]
    known = {s["id"] for s in sections}
    for lesson in data["lessons"]:
        if lesson["section"] not in known:
            print(f"error: {lesson['id']}: unknown section {lesson['section']!r}", file=sys.stderr)
            return 1
        if not (ROOT / "src" / "gallery" / lesson["cover"]).is_file():
            print(f"error: {lesson['id']}: cover not found: {lesson['cover']}", file=sys.stderr)
            return 1

    parts = [HEAD]
    parts.append("""  <div class="wrap page-head">
    <h1 class="page-title">見本</h1>
    <p class="page-lead">どれも Egatari で作った教材です。ダウンロードしたファイルは、ブラウザで開けば再生できます。編集できる版は、編集アプリで開くと中を見られます。</p>
    <ul class="toc">
""")
    for s in sections:
        parts.append(f'      <li><a href="#{escape(s["id"])}">{escape(s["title"])}</a></li>\n')
    parts.append("    </ul>\n  </div>\n\n")

    for s in sections:
        sid = escape(s["id"])
        parts.append(f'  <section class="gsec" id="{sid}" aria-labelledby="h-{sid}">\n    <div class="wrap">\n')
        parts.append(f'      <h2 id="h-{sid}">{escape(s["title"])}</h2>\n')
        if s.get("subtitle"):
            parts.append(f'      <p class="sub">{escape(s["subtitle"])}</p>\n')
        parts.append('      <ul class="cards">\n')
        for lesson in data["lessons"]:
            if lesson["section"] == s["id"]:
                parts.append(card(lesson, base, bool(data.get("play_live"))))
        parts.append("      </ul>\n    </div>\n  </section>\n\n")

    parts.append(FOOT)
    OUT.write_text("".join(parts), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(data['lessons'])} lessons)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
